import { chromium, expect } from '@playwright/test';
import { createServer } from 'vite';
import { fileURLToPath } from 'node:url';
import { mkdir } from 'node:fs/promises';
const root = fileURLToPath(new URL('../', import.meta.url));
const output = fileURLToPath(new URL('../../../docs/previews/', import.meta.url));
await mkdir(output, { recursive: true });
const server = await createServer({ root, server: { open: false, port: 8081, strictPort: true } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1 });
  const errors = [];
  let apiCalls = 0;
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().includes('/api/')) apiCalls++; });
  await page.goto('http://localhost:8081/?preview=create-player');
  await page.getByRole('heading', { name: "What’s your name?" }).waitFor();
  await page.evaluate(async () => { await document.fonts.ready; await Promise.all([...document.images].map(image => image.decode().catch(() => {}))); });
  if (await page.locator('html').getAttribute('lang') !== 'en') throw new Error('Default language is not English');
  await page.locator('#g-player-name').fill('Moonleaf');
  const play = page.getByRole('button', { name: "Let's play", exact: true });
  await play.evaluate(button => { button.disabled = true; });
  const disabledBounds = await play.boundingBox();
  await page.mouse.click(disabledBounds.x + disabledBounds.width / 2, disabledBounds.y + disabledBounds.height / 2);
  await expect(page.locator('#g-create-form')).toBeVisible();
  await play.evaluate(button => { button.disabled = false; });
  await page.mouse.move(0, 0);
  await page.screenshot({ path: output + 'create-player-desktop.png', fullPage: true, animations: 'disabled' });
  const frame = await page.locator('.g-create-panel').boundingBox();
  await page.screenshot({
    path: output + 'create-player-frame.png',
    clip: { x: frame.x - 16, y: frame.y - 16, width: frame.width + 32, height: frame.height + 48 },
    animations: 'disabled',
  });
  if (await page.getByRole('dialog').count()) throw new Error('Avatar picker must start hidden');
  await page.getByText('Welcome to Gemora!', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Change avatar', exact: true }).click();
  await page.screenshot({ path: output + 'avatar-picker-desktop.png', fullPage: true, animations: 'disabled' });
  await page.keyboard.press('Escape');
  if (!await page.getByRole('button', { name: 'Change avatar', exact: true }).evaluate(el => el === document.activeElement)) throw new Error('Picker failed to restore focus');
  await page.getByRole('button', { name: 'Change avatar', exact: true }).click();
  await page.getByRole('button', { name: 'Sun', exact: true }).click();
  if (await page.locator('#g-player-name').inputValue() !== 'Moonleaf') throw new Error('Name lost when changing avatar');
  await page.getByRole('button', { name: 'Change avatar', exact: true }).click();
  await page.getByRole('button', { name: 'Crystal dragon', exact: true }).click();
  await page.locator('#g-player-name').focus();
  await page.keyboard.press('Tab');
  await expect(play).toBeFocused();
  await expect(play).toHaveCSS('outline-style', 'solid');
  await page.keyboard.down('Space');
  await expect(play).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 3)');
  await page.keyboard.up('Space');
  await page.getByRole('button', { name: 'Moonleaf' }).waitFor();
  await page.getByText('Welcome, Moonleaf!', { exact: true }).waitFor();
  await page.evaluate(async () => { await Promise.all([...document.images].map(image => image.decode().catch(() => {}))); });
  await page.screenshot({ path: output + 'home-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Moonleaf' }).click();
  await page.getByRole('button', { name: 'Change avatar', exact: true }).click();
  await page.getByRole('button', { name: 'Sun', exact: true }).click();
  if (!await page.locator('.g-player-card .g-avatar-circle.gold').count()) throw new Error('Profile avatar change failed');
  await page.getByRole('button', { name: 'Moonleaf' }).click();
  await page.getByRole('button', { name: 'Change avatar', exact: true }).click();
  await page.getByRole('button', { name: 'Crystal dragon', exact: true }).click();
  await page.getByRole('button', { name: /ARENA/ }).click();
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  if (await page.getByRole('dialog').count()) throw new Error('Dialog did not close');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: output + 'home-mobile.png', fullPage: true, animations: 'disabled' });
  if (!await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)) throw new Error('Home overflows mobile viewport');
  await page.getByRole('button', { name: 'Create player' }).click();
  await page.locator('#g-player-name').fill('a');
  await page.getByRole('button', { name: "Let's play" }).click();
  if (!await page.locator('#g-name-error').textContent()) throw new Error('Invalid name was accepted');
  await page.locator('#g-player-name').fill('Moonleaf');
  const mobilePlayBounds = await play.boundingBox();
  if (mobilePlayBounds.height < 54 || mobilePlayBounds.height > 60) throw new Error('Mobile play button height must be 54–60px');
  await page.screenshot({ path: output + 'create-player-mobile.png', fullPage: true, animations: 'disabled' });
  if (!await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)) throw new Error('Create screen overflows mobile viewport');
  await page.goto('http://localhost:8081/?preview=home');
  await page.getByText('Welcome back, Moonleaf!', { exact: true }).waitFor();
  if (errors.length) throw new Error(errors.join('\n'));
  if (apiCalls) throw new Error('Preview must not call account APIs');
  console.log('Captured both screens at 1440px and 390px. Name, avatar, navigation, dialog, validation and API isolation checks passed.');
} finally {
  await browser?.close();
  await server.close();
}
